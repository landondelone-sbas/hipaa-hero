/* ============================================================================
   HIPAA HERO — build-standalone.js   (OPTIONAL)
   ----------------------------------------------------------------------------
   Inlines every stylesheet and script into one self-contained HTML file:

       hipaa-hero-standalone.html

   Why this exists: the modular version relies on relative paths
   (css/…, js/…, data/…). If someone copies index.html on its own — emails it,
   drags it to a Desktop, saves it out of a chat window — those paths break and
   the page renders as unstyled text. The standalone build has no external
   references at all, so it survives being moved anywhere.

   The modular version in this folder is still the source of truth and needs
   no build step to run. Use this only when you want a single distributable
   file. Re-run it after editing anything in data/.

   Usage:   node build-standalone.js
   ============================================================================ */

const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const OUT  = path.join(ROOT, "hipaa-hero-standalone.html");

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), "utf8");
}

/* Guard against a literal "</script>" inside data strings ending the block
   early. None exists today, but content is edited by non-developers. */
function safeForInlineScript(js) {
  return js.replace(/<\/script>/gi, "<\\/script>");
}

let html = read("index.html");

// Replace each <link rel="stylesheet" href="css/..."> with an inline <style>
html = html.replace(
  /[ \t]*<link rel="stylesheet" href="(css\/[^"]+)">\n?/g,
  function (_, href) {
    return "<style>\n/* ===== " + href + " ===== */\n" + read(href) + "\n</style>\n";
  }
);

// Replace each <script src="..."> with the file's contents inline
html = html.replace(
  /[ \t]*<script src="((?:js|data)\/[^"]+)"><\/script>\n?/g,
  function (_, src) {
    return "<script>\n/* ===== " + src + " ===== */\n" +
           safeForInlineScript(read(src)) + "\n</script>\n";
  }
);

// Replace each <img src="assets/..."> with a base64 data URI
const MIME_BY_EXT = { png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg",
                       svg: "image/svg+xml", webp: "image/webp", gif: "image/gif" };

html = html.replace(
  /(<img[^>]*\bsrc=")(assets\/[^"]+)(")/g,
  function (_, pre, src, post) {
    const ext  = path.extname(src).slice(1).toLowerCase();
    const mime = MIME_BY_EXT[ext] || "application/octet-stream";
    const b64  = fs.readFileSync(path.join(ROOT, src)).toString("base64");
    return pre + "data:" + mime + ";base64," + b64 + post;
  }
);

html = html.replace(
  "<title>",
  "<!-- SELF-CONTAINED BUILD — generated by build-standalone.js.\n" +
  "     Do not edit directly; edit the files in data/ and re-run the script. -->\n<title>"
);

fs.writeFileSync(OUT, html, "utf8");

/* Verify nothing external survived the inlining. */
const leftovers = (html.match(/(?:src|href)="(?!https?:|data:|#)[^"]+"/g) || []);
const kb = (Buffer.byteLength(html, "utf8") / 1024).toFixed(0);

console.log("Wrote " + path.basename(OUT) + "  (" + kb + " KB)");
console.log(leftovers.length
  ? "WARNING — unresolved local references: " + leftovers.join(", ")
  : "No local file references remain. Safe to move or email anywhere.");
